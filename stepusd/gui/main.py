    def _body_size(self, proto, bi):
        """Largest dimension of one body, for the relative mode."""
        key = (proto.key, bi)
        got = self._body_size_cache.get(key)
        if got is None:
            from OCP.Bnd import Bnd_Box
            from OCP.BRepBndLib import BRepBndLib
            bb = Bnd_Box()
            try:
                BRepBndLib.Add_s(proto.bodies[bi], bb, False)
                x0, y0, z0, x1, y1, z1 = bb.Get()
                got = max(x1 - x0, y1 - y0, z1 - z0)
            except Exception:
                got = 0.0
            self._body_size_cache[key] = got
        return got

    def _tuning_targets(self):
        """Which bodies the quality panel is currently driving.

        While something is ISOLATED, the panel drives everything on screen --
        that is the point of isolating, and having to also select the parts was
        busywork. With nothing isolated it falls back to the selection, which is
        where per-part tuning belongs.
        """
        out = set()
        if self._hidden:                       # something is isolated
            for (path, bi) in self._body_items:
                if (path, bi) in self._hidden:
                    continue
                occ = self._occ_by_path.get(path)
                if occ is not None:
                    out.add((occ.proto_key, bi))
            return out
        for path, bi in self._selected_keys():
            occ = self._occ_by_path.get(path)
            if occ is None:
                continue
            key = (occ.proto_key, bi)
            if key in self._quality:
                continue          # it has a quality of its own: leave it alone
            out.add(key)
        return out

    def _param_changed(self, *_):
        if self._loading_panel:
            return                      # the panel is being filled in, not edited
        if self.doc:
            live = self._params()
            targets = self._tuning_targets()
            if targets:
                for k in targets:
                    self._custom[k] = live
                    # Only ISOLATED targets can still carry a preset here --
                    # the selection branch of _tuning_targets drops those -- and
                    # while isolated the panel is meant to drive everything on
                    # screen. Clearing it keeps the outliner honest: _params_for
                    # reads _custom first, so leaving the preset name showing
                    # would be a lie about what the body is actually meshed at.
                    self._quality.pop(k, None)
                self._refresh_tree_labels()
                if self.cb_color.currentIndex() == 3:
                    # the custom ramp rescales to the values in use, so every
                    # tuned body can change colour when any one of them moves
                    self._recolor()
            else:
                self._base = live       # nothing selected: this is the default
        if self.c_live.isChecked():
            self._debounce.start()

    def _params(self) -> MeshParams:
        mn = self.s_min.value()
        return MeshParams(deflection=self.s_defl.value(),
                          angle_deg=self.s_angle.value(),
                          min_size=(mn if mn > 0 else -1.0),
                          relative=self.c_relative.isChecked(),
                          structured=self.c_structured.isChecked(),
                          grid_aspect=self.s_aspect.value(),
                          quads=self.c_quads.isChecked(),
                          lattice=self.c_iso.isChecked(),
                          grid_trim=self.c_iso.isChecked(),
                          auto_grid=self.c_autogrid.isChecked(),
                          grid_bias=self.s_bias.value() / 100.0)

    def _preset(self, name):
        for p in self.presets:
            if p["name"] == name:
                return p
        return None

    def _params_for(self, proto, bi=0):
        """Quality for ONE body: its own override, then a preset, then the base.

        Keyed per body, not per part: a SolidWorks surface-model export can put
        164 bodies inside one part, and keying by part would move all of them.

        The quality panel edits the SELECTION, so bodies without an override sit
        on `_base` and are not disturbed -- their cache signatures stay put and
        the worker re-meshes only what actually changed. "Apply to EVERY part"
        is the one action that moves `_base`.
        """
        key = (proto.key, bi)
        got = self._custom.get(key)
        if got is not None:
            return self._with_cuts(self._as_mm(got, proto, bi), proto, bi)
        base = self._base or self._params()
        pr = self._preset(self._quality.get(key))
        if pr is None:
            return self._with_cuts(self._as_mm(base, proto, bi), proto, bi)
        out = replace(base, deflection=pr["deflection"], angle_deg=pr["angle"])
        if pr.get("quads") is not None:
            out = replace(out, quads=bool(pr["quads"]))
        if pr.get("grid") is not None:
            out = replace(out, structured=bool(pr["grid"]))
        if pr.get("iso") is not None:
            out = replace(out, lattice=bool(pr["iso"]),
                          grid_trim=bool(pr["iso"]))
        return self._with_cuts(self._as_mm(out, proto, bi), proto, bi)

    def _with_cuts(self, q, proto, bi):
        """Attach this body's forced loop cuts to its params.

        They ride on MeshParams so they land in the mesh-cache signature: add
        or remove a cut and the body re-meshes, exactly like any other setting.
        """
        chains = self._iso_cuts.get((proto.key, bi))
        if not chains:
            return q
        flat = tuple(c for chain in chains for c in chain)
        return replace(q, iso_cuts=flat) if flat else q

    def _as_mm(self, q, proto, bi):
        """Turn a percentage deviation into millimetres for THIS body.

        The mesher only ever sees millimetres; the percentage is a UI unit.
        OCCT's own `Relative` flag is deliberately not used -- it scales to each
        EDGE's length, which is not what "relative to part size" means to a
        person looking at an assembly of big and small parts.
        """
        if not q.relative:
            return q
        size = self._body_size(proto, bi)
        if size <= 0:
            return replace(q, relative=False)
        return replace(q, relative=False,
                       deflection=max(1e-6, q.deflection * 0.01 * size))

