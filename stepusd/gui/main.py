    def _tess_done(self, meshes, secs, gen):
        if gen != self._generation:
            return                          # a newer drag already superseded this
        self.meshes = meshes
        if self._rebuild:
            self._rebuild_palette()
            self.viewport.build(meshes, self.occurrences, self._color_for,
                                self._face_rgb)
            self.viewport.set_edges(self.c_edges.isChecked())
            self.viewport.set_hidden(self._hidden)
            self.viewport.set_view("iso")
        else:
            self.viewport.update_meshes(meshes, self._face_rgb)
            self.viewport.set_colors(self._color_for)
        self.viewport.set_face_color_mode(self._face_colors_active)
        self._update_body_flags()
        self._update_stats(secs)
        self.a_export.setEnabled(True)
        self.a_export_sel.setEnabled(bool(self._selected_keys()))
        self._selection_changed()

    def _update_stats(self, secs):
        authored = sum(len(m.tris) for ms in self.meshes.values() for m in ms)
        placed = 0
        counts = {k: sum(len(m.tris) for m in ms) for k, ms in self.meshes.items()}
        for occ in self.occurrences:
            placed += counts.get(occ.proto_key, 0)
        leaks = [(k, m) for k, ms in self.meshes.items() for m in ms
                 if not m.watertight]
        holes = sum(1 for _, m in leaks if m.boundary_edges)
        nonman = sum(1 for _, m in leaks if m.nonmanifold_edges)
        flaps = sum(m.removed_flaps for ms in self.meshes.values() for m in ms)
        nq = sum(m.n_quads for ms in self.meshes.values() for m in ms)
        nf = sum(len(m.faces) for ms in self.meshes.values() for m in ms)
        self.l_tris.setText(f"{authored:,} authored / {placed:,} placed")
        self.l_quads.setText(f"{nq:,} of {nf:,} faces" if nf else "-")
        open_shells = sum(p.open_bodies for p in self.doc.protos.values())
        # A surface defect does NOT make a body un-watertight -- that is exactly
        # what made it invisible -- so it has to be checked before `leaks`.
        defects = sum(1 for ms in self.meshes.values() for m in ms
                      if getattr(m, "surface_defects", 0))
        dropped = sum(getattr(m, "iso_cuts_dropped", 0)
                      for ms in self.meshes.values() for m in ms)
        if dropped:
            self._say(f"{dropped} forced loop cut(s) refused: they would have "
                      f"opened the body, so the mesh was kept sealed instead")
        nil = sum(getattr(m, "iso_cuts_ineffective", 0)
                  for ms in self.meshes.values() for m in ms)
        if nil:
            self._say(f"{nil} forced loop cut(s) divided nothing -- the "
                      f"surface there was already split by a real CAD edge")
        if defects:
            self.l_water.setText(f"{defects} with SURFACE ERRORS")
            self.l_water.setStyleSheet("color:#f55; font-weight:bold")
            self.l_water.setToolTip(
                "A face is missing real surface area: OCCT under-meshed it and "
                "no honest repair was possible. The body can still report as "
                "sealed and still be WRONG -- look for the red rows in the "
                "outliner. A coarser max surface deviation usually avoids it.")
        elif not leaks:
            self.l_water.setText("all bodies sealed")
            self.l_water.setStyleSheet("color:#2a2; font-weight:bold")
            self.l_water.setToolTip("")
        elif holes <= open_shells and nonman == 0:
            # only the bodies that were never closed solids to begin with
            self.l_water.setText(f"{holes} open shell(s) - not solids")
            self.l_water.setStyleSheet("color:#d80; font-weight:bold")
            self.l_water.setToolTip(
                "These bodies arrived as open shells rather than closed solids, "
                "so they cannot be sealed. Every real solid is watertight.")
        else:
            names = {self.doc.protos[k].name for k, _ in leaks}
            bits = []
            if holes:
                bits.append(f"{holes} with holes")
            if nonman:
                bits.append(f"{nonman} non-manifold")
            self.l_water.setText(", ".join(bits))
            self.l_water.setStyleSheet("color:#d33; font-weight:bold")
            self.l_water.setToolTip(", ".join(sorted(names)))
        if flaps:
            prev = self.l_water.toolTip()
            note = f"repaired {flaps} zero-volume triangle flap(s)"
            self.l_water.setToolTip(f"{prev}\n{note}" if prev else note)
        ngrid = sum(m.structured_faces for ms in self.meshes.values() for m in ms)
        self.l_grid.setText(str(ngrid))
        self.l_time.setText(f"{secs:.2f} s")
        self.statusBar().showMessage(
            f"{authored:,} triangles authored, {placed:,} as placed  |  {secs:.2f}s")

    def _body_sizes(self):
        """{(occurrence.path, body_index): bounding-box diagonal in mm}."""
        if getattr(self, "_sizes", None):
            return self._sizes
        from OCP.Bnd import Bnd_Box
        from OCP.BRepBndLib import BRepBndLib
        import math as _m
        per_proto = {}
        for key, proto in self.doc.protos.items():
            dims = []
            for b in proto.bodies:
                box = Bnd_Box()
                try:
                    BRepBndLib.Add_s(b, box, False)
                    x0, y0, z0, x1, y1, z1 = box.Get()
                    dims.append(_m.dist((x0, y0, z0), (x1, y1, z1)))
                except Exception:
                    dims.append(0.0)
            per_proto[key] = dims
        out = {}
        for occ in self.occurrences:
            for bi, d in enumerate(per_proto.get(occ.proto_key, [])):
                out[(occ.path, bi)] = d
        self._sizes = out
        return out

