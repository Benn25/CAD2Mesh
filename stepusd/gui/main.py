class LogSlider(QWidget):
    """Slider + spinbox on a log scale -- deflection spans 0.001..10, which a
    linear slider cannot control usefully."""
    changed = Signal(float)

    def __init__(self, lo: float, hi: float, value: float, decimals=4, suffix=""):
        super().__init__()
        self.lo, self.hi = lo, hi
        lay = QHBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        self.slider = QSlider(Qt.Horizontal)
        self.slider.setRange(0, 1000)
        self.spin = QDoubleSpinBox()
        self.spin.setDecimals(decimals)
        self.spin.setRange(lo, hi)
        self.spin.setSuffix(suffix)
        self.spin.setMaximumWidth(96)
        lay.addWidget(self.slider, 1)
        lay.addWidget(self.spin)
        self._guard = False
        self.slider.valueChanged.connect(self._from_slider)
        self.spin.valueChanged.connect(self._from_spin)
        self.set_value(value)

    def set_min(self, lo: float):
        """Move the lower bound. The slider is logarithmic, so the whole
        mapping shifts with it; keep the current value if it still fits."""
        cur = self.value()
        self.lo = lo
        self.spin.setRange(lo, self.hi)
        self.set_value(max(lo, cur))

    def _to_pos(self, v):
        v = max(self.lo, min(self.hi, v))
        return int(1000 * (math.log10(v) - math.log10(self.lo)) /
                   (math.log10(self.hi) - math.log10(self.lo)))

    def _to_val(self, p):
        return 10 ** (math.log10(self.lo) + (p / 1000.0) *
                      (math.log10(self.hi) - math.log10(self.lo)))

    def _from_slider(self, p):
        if self._guard:
            return
        self._guard = True
        v = self._to_val(p)
        self.spin.setValue(v)
        self._guard = False
        self.changed.emit(v)

    def _from_spin(self, v):
        if self._guard:
            return
        self._guard = True
        self.slider.setValue(self._to_pos(v))
        self._guard = False
        self.changed.emit(v)

    def value(self):
        return self.spin.value()

    def set_range(self, lo, hi):
        """Re-scale to the data actually present, so the whole travel is useful."""
        if hi <= lo:
            hi = lo * 10.0 or 1.0
        self.lo, self.hi = max(1e-6, lo), hi
        cur = min(max(self.spin.value(), self.lo), self.hi)
        self._guard = True
        self.spin.setRange(self.lo, self.hi)
        self.spin.setValue(cur)
        self.slider.setValue(self._to_pos(cur))
        self._guard = False

    def set_value(self, v):
        self._guard = True
        self.spin.setValue(max(self.lo, min(self.hi, v)))
        self.slider.setValue(self._to_pos(v))
        self._guard = False


class LinSlider(QWidget):
    changed = Signal(float)

    def __init__(self, lo, hi, value, decimals=1, suffix="", step=0.5):
        super().__init__()
        lay = QHBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        self.scale = 1 / step
        self.slider = QSlider(Qt.Horizontal)
        self.slider.setRange(int(lo * self.scale), int(hi * self.scale))
        self.spin = QDoubleSpinBox()
        self.spin.setDecimals(decimals)
        self.spin.setRange(lo, hi)
        self.spin.setSingleStep(step)
        self.spin.setSuffix(suffix)
        self.spin.setMaximumWidth(96)
        lay.addWidget(self.slider, 1)
        lay.addWidget(self.spin)
        self._guard = False
        self.slider.valueChanged.connect(self._from_slider)
        self.spin.valueChanged.connect(self._from_spin)
        self.set_value(value)

    def _from_slider(self, p):
        if self._guard:
            return
        self._guard = True
        v = p / self.scale
        self.spin.setValue(v)
        self._guard = False
        self.changed.emit(v)

    def _from_spin(self, v):
        if self._guard:
            return
        self._guard = True
        self.slider.setValue(int(v * self.scale))
        self._guard = False
        self.changed.emit(v)

    def value(self):
        return self.spin.value()

    def set_value(self, v):
        self._guard = True
        self.spin.setValue(v)
        self.slider.setValue(int(v * self.scale))
        self._guard = False


def _nice(x: float) -> float:
    """Snap to a number a person would have typed: 1, 1.25, 1.5, 2, 2.5, ..."""
    if x <= 0:
        return x
    import math as _m
    e = _m.floor(_m.log10(x))
    base = x / (10.0 ** e)
    best = min((1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0, 6.0, 8.0, 10.0),
               key=lambda c: abs(c - base))
    return best * (10.0 ** e)


