    def _mesh_of(self, proto_key, bi):
        ms = self.meshes.get(proto_key)
        if ms and bi < len(ms):
            return ms[bi]
        return None

    def _custom_deflection_range(self):
        """(min, max) deviation across every body carrying a CUSTOM quality."""
        vals = [q.deflection for q in self._custom.values() if q.deflection > 0]
        if not vals:
            return None
        return min(vals), max(vals)

    def _custom_quality_color(self, defl):
        """Blue ramp over the custom deviations actually in use.

        Deep blue is the finest value in the model, light blue the coarsest, so
        the ramp rescales itself to whatever range is being tuned rather than to
        an absolute scale that would put everything at one end. Only the max
        surface deviation feeds it -- the angle and the switches say nothing
        about how fine a part looks.

        The dark end stops well short of black: the wireframe is drawn in black
        and has to stay readable on top of it.
        """
        rng = self._custom_deflection_range()
        if rng is None:
            return presets_mod.NO_PRESET_COLOR
        lo, hi = rng
        t = 0.5 if hi <= lo else (defl - lo) / (hi - lo)
        t = max(0.0, min(1.0, t))
        # deep but not dark blue -> pale blue
        a = (0.16, 0.30, 0.62)
        b = (0.70, 0.86, 0.98)
        return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))

    def _color_for(self, occ, bi):
        """Bodies that are not closed solids always win, whatever the mode:
        the point is to SEE where they are."""
        m = self._mesh_of(occ.proto_key, bi)
        if m is not None and not m.watertight:
            return OPEN_SHELL_COLOR if m.boundary_edges else NONMANIFOLD_COLOR
        mode = self.cb_color.currentIndex()
        if mode == 3:
            key = (occ.proto_key, bi)
            if key in self._custom:
                return self._custom_quality_color(self._custom[key].deflection)
            pr = self._preset(self._quality.get(key))
            if pr is None:
                return presets_mod.NO_PRESET_COLOR
            return tuple(pr.get("color") or presets_mod.NO_PRESET_COLOR)
        if mode == 1:
            return self._component_colors.get((occ.path, bi), DEFAULT_COLOR)
        if mode == 2:
            return self._proto_colors.get(occ.proto_key, DEFAULT_COLOR)
        proto = self.doc.protos.get(occ.proto_key)
        if proto is not None:
            bc = getattr(proto, "body_colors", None)
            if bc and bi < len(bc) and bc[bi]:
                return bc[bi]
            if proto.color:
                return proto.color
        return DEFAULT_COLOR

    SURFACE_TYPE_MODE = 4

    def _face_rgb(self, proto_key, bi):
        """Per-triangle colours for one body, from its per-face STEP colours.
        Returns None when the body has no face colours of its own."""
        proto = self.doc.protos.get(proto_key)
        m = self._mesh_of(proto_key, bi)
        if proto is None or m is None or not m.face_source:
            return None
        if self.cb_color.currentIndex() == self.SURFACE_TYPE_MODE:
            return self._surface_type_rgb(m)
        fcs = proto.body_face_colors
        if bi >= len(fcs):
            return None
        faces = fcs[bi]
        if not any(faces):
            return None
        fallback = proto.color or DEFAULT_COLOR
        import numpy as np
        table = np.array([[*(c or fallback)] for c in faces], dtype=np.float32)
        # one colour per emitted POLYGON (VTK cell), so use face_source
        idx = np.asarray(m.face_source, dtype=np.int64) - 1
        idx = np.clip(idx, 0, len(faces) - 1)
        return (table[idx] * 255.0 + 0.5).astype(np.uint8)

    def _surface_type_rgb(self, m):
        """One colour per POLYGON from the B-rep surface type behind it."""
        if not m.face_kinds:
            return None
        import numpy as np
        table = np.array(
            [[*surface_type_color(k)] for k in m.face_kinds], dtype=np.float32)
        idx = np.asarray(m.face_source, dtype=np.int64)
        idx = np.clip(idx, 0, len(m.face_kinds) - 1)
        return (table[idx] * 255.0 + 0.5).astype(np.uint8)

    def _face_colors_active(self, proto_key, bi):
        """Per-face colours are used only in Material and surface-type modes,
        and never on a body we need to flag or that is selected: those colours
        must win."""
        if self.cb_color.currentIndex() == self.SURFACE_TYPE_MODE:
            m = self._mesh_of(proto_key, bi)
            if m is None or not m.face_kinds:
                return False
            sel = self.viewport._selected
            return (proto_key, bi) not in {
                (self._occ_by_path[p].proto_key, b)
                for p, b in sel if p in self._occ_by_path}
        if self.cb_color.currentIndex() != 0:
            return False
        m = self._mesh_of(proto_key, bi)
        if m is not None and not m.watertight:
            return False
        sel = self.viewport._selected
        for occ in self.occurrences:
            if occ.proto_key == proto_key and (occ.path, bi) in sel:
                return False
        return self._face_rgb(proto_key, bi) is not None

    def _arm_loopcut(self, on):
        """While armed, a click in the 3D view adds a cut instead of selecting,
        and hovering previews where that cut would land."""
        self.viewport._cell_cb = self._add_loopcut if on else None
        self.viewport._hover_cb = self._preview_loopcut if on else None
        self.viewport._rmb_cb = self._on_cut_rmb if on else None
        self.viewport._wheel_cb = self._follow_wheel if on else None
        # Shift changes what a click does, so its state has to be visible
        # BEFORE the mouse moves again -- hence a watcher, not a modifier read.
        self.viewport.watch_modifiers(self._cut_modifier if on else None)
        self.l_cutkeys.setVisible(bool(on))
        if on:
            self._draw_existing_cuts()
        else:
            self.viewport.clear_iso_preview()
            self.viewport.clear_cut_lines()
            self.viewport.clear_snap_marker()
            self.viewport.set_action_cursor(None)
            self._last_hover = None
            self._hover_cut = None
            self._hover_doomed = ()
        self._say("hover to preview, click to cut, right-click removes"
                  if on else "loop cut off")

    def _cut_modifier(self, shift):
        """Shift went down or up: redraw, since it changes what a click does."""
        self._refresh_cut_preview()

    def _push_cut_undo(self):
        """Snapshot the cuts before changing them.

        A cut can take a while to place, so losing one to a mis-click and
        having no way back is exactly the pain this is here to avoid. Cheap to
        keep: a handful of tuples per body.
        """
        snap = {k: [list(c) for c in v] for k, v in self._iso_cuts.items()}
        self._cut_undo.append(snap)
        del self._cut_undo[:-64]

    def _undo_cut(self):
        """Ctrl+Z: step back through the loop-cut history."""
        if not self._cut_undo:
            self._say("nothing to undo")
            return
        self._iso_cuts = self._cut_undo.pop()
        self._hover_cut = None
        n = sum(len(c) for v in self._iso_cuts.values() for c in v)
        self._say(f"undo: {n} cut stretch(es) remain")
        if self.c_loopcut.isChecked():
            self._draw_existing_cuts()
        self._retessellate()

    def _follow_wheel(self, step, shift=False):
        """Ctrl+wheel: how far a cut travels -- or, with shift held, how many
        consecutive stretches a removal takes.

        One binding, read in the context the cursor is already in: shift is
        what turns the tool from cutting into removing, so it is also what
        decides which quantity the wheel is setting.
        """
        if shift:
            self._remove_span = max(1, min(200, self._remove_span + step))
            self._say(f"a removal takes {self._remove_span} "
                      f"consecutive stretch(es)")
        else:
            self._max_follow = max(1, min(200, self._max_follow + step))
            self._say(f"cut may cross up to {self._max_follow} surface(s)")
        self._refresh_cut_preview()

    def _cut_strips(self, pk, bi):
        """[(chain index, stretch index, points)] for every existing cut.

        Memoised on the cuts themselves, because this runs on every mouse MOVE
        while the tool is armed and each stretch costs 160 surface evaluations
        plus 160 `BRepTopAdaptor_FClass2d` classifications. The cuts only change
        on a click, so the cache key is simply what they are.
        """
        chains = self._iso_cuts.get((pk, bi), ())
        key = (pk, bi, tuple(tuple(c) for c in chains))
        got = self._strip_cache.get(key)
        if got is not None:
            return got
        out = []
        for ci, chain in enumerate(chains):
            for si, (cf, cd, cp) in enumerate(chain):
                pts = self._iso_points(pk, bi, cf, cd, cp)
                if len(pts) >= 2:
                    out.append((ci, si, pts))
        # `_draw_existing_cuts` walks EVERY body carrying cuts, so clearing on
        # each insert would evict the entry the next call wants. Bound it by
        # size instead; a stale key can never be read, since the key IS the
        # cuts.
        if len(self._strip_cache) > 32:
            self._strip_cache.clear()
        self._strip_cache[key] = out
        return out

    def _draw_existing_cuts(self, hot=None):
        """Show every existing cut in red; `hot` glows instead.

        `hot` is (proto key, body, chain, {stretch indices}) -- a SUBSET of one
        chain, not the whole of it, because that is what a click would remove.
        """
        if not self.doc or not self.meshes:
            return
        cold, warm = [], []
        for (pk, bi) in self._iso_cuts:
            for ci, si, pts in self._cut_strips(pk, bi):
                doomed = (hot is not None and (pk, bi, ci) == hot[:3]
                          and si in hot[3])
                (warm if doomed else cold).append(pts)
        self.viewport.show_cut_lines(cold, hot=warm)

    def _removal_set(self, pk, bi, ci, si, n):
        """Which stretches a removal takes: the hovered one plus its n-1
        nearest NEIGHBOURS along the cut.

        Grown by 3D proximity rather than by list index, because a propagated
        chain is stored as seed-then-one-way-then-the-other: consecutive in
        that list is not consecutive on the part. Endpoint distance is the
        right measure -- stretches meet end to end at the edges they cross.
        """
        chains = self._iso_cuts.get((pk, bi), ())
        if ci >= len(chains):
            return set()
        chain = chains[ci]
        ends = {k: (pts[0], pts[-1])
                for c, k, pts in self._cut_strips(pk, bi) if c == ci}
        take = {si}
        while len(take) < n and len(take) < len(chain):
            best = None
            for k in range(len(chain)):
                if k in take or k not in ends:
                    continue
                d = min((math.dist(a, b)
                         for j in take if j in ends
                         for a in ends[j] for b in ends[k]), default=None)
                if d is not None and (best is None or d < best[0]):
                    best = (d, k)
            if best is None:
                break
            take.add(best[1])
        return take

    def _find_hovered_cut(self, pk, bi, fi, u, v):
        """Which existing cut is under the cursor: (chain, stretch) or None.

        Compared in the surface's OWN parameters, not in space: a cut IS an
        isocurve, so asking whether the cursor is on it is just asking whether
        the parameter matches, which is exact and costs nothing.
        """
        chains = self._iso_cuts.get((pk, bi))
        if not chains:
            return None
        try:
            from OCP.TopExp import TopExp
            from OCP.TopAbs import TopAbs_ShapeEnum
            from OCP.TopoDS import TopoDS
            from OCP.TopTools import TopTools_IndexedMapOfShape
            from OCP.BRepTools import BRepTools
            proto = self.doc.protos[pk]
            faces = TopTools_IndexedMapOfShape()
            TopExp.MapShapes_s(proto.bodies[bi], TopAbs_ShapeEnum.TopAbs_FACE,
                               faces)
            if fi < 1 or fi > faces.Extent():
                return None
            u0, u1, v0, v1 = BRepTools.UVBounds_s(
                TopoDS.Face_s(faces.FindKey(fi)))
        except Exception:
            return None
        best = None
        for ci, chain in enumerate(chains):
            for si, (cf, cd, cp) in enumerate(chain):
                if cf != fi:
                    continue
                here = u if cd == "U" else v
                span = (u1 - u0) if cd == "U" else (v1 - v0)
                if span <= 0:
                    continue
                d = abs(here - cp) / span
                if d < 0.02 and (best is None or d < best[0]):
                    best = (d, ci, si)
        return None if best is None else (best[1], best[2])

    def _on_cut_rmb(self, shift=False):
        """Right-click: remove the cut under the cursor, else swap U/V.

        Shift narrows it to the glowing stretches instead of the whole chain.
        Removal is bound HERE and nowhere else, so nothing a left click can do
        will ever destroy a cut.
        """
        if self._hover_cut is not None:
            self._delete_hovered_cut(whole=not shift)
        else:
            self._swap_uv()

    def _delete_hovered_cut(self, whole=True):
        """Remove the hovered cut: the whole chain, or just this stretch.

        Preparing a cut can take a while, so losing all of them because one
        stretch is wrong would be painful -- hence both granularities.
        """
        if self._hover_cut is None:
            return
        pk, bi, ci, si = self._hover_cut
        chains = list(self._iso_cuts.get((pk, bi), ()))
        if ci >= len(chains):
            return
        self._push_cut_undo()
        if whole:
            n = len(chains.pop(ci))
            what = f"removed a cut of {n} stretch(es)"
        else:
            drop = self._hover_doomed or {si}
            chain = [x for k, x in enumerate(chains[ci]) if k not in drop]
            if chain:
                chains[ci] = chain
            else:
                chains.pop(ci)
            what = f"removed {len(drop)} stretch(es) of a cut"
        if chains:
            self._iso_cuts[(pk, bi)] = chains
        else:
            self._iso_cuts.pop((pk, bi), None)
        self._hover_cut = None
        self._say(what)
        self._retessellate()

    def _swap_uv(self):
        """Right-click while cutting: flip between the two isocurve families."""
        self.cb_uv.setCurrentIndex(1 - self.cb_uv.currentIndex())
        self._say(f"cut direction {self.cb_uv.currentText()}")
        self._refresh_cut_preview()

    def _refresh_cut_preview(self):
        """Redraw the preview for the last thing hovered, after a settings
        change -- swapping U/V with the cursor still is otherwise invisible."""
        if getattr(self, "_last_hover", None) is not None:
            self._preview_loopcut(self._last_hover)

    def _cut_chain(self, pk, bi, fi, direction, param):
        """The cuts one click would make: just this one, or the whole tangent
        chain when "continue across tangent edges" is on."""
        seed = [(fi, direction, float(param))]
        self._last_chain_closed = False
        if not self.c_followcut.isChecked():
            return seed
        proto = self.doc.protos.get(pk)
        if proto is None or bi >= len(proto.bodies):
            return seed
        try:
            from .. import tessellate as _T
            got = _T.propagate_iso_cut(proto.bodies[bi], fi, direction, param,
                                       max_steps=self._max_follow)
            self._last_chain_closed = bool(_T.LAST_LOOP_CLOSED)
            return got or seed
        except Exception:
            self._last_chain_closed = False
            return seed

    def _iso_points(self, pk, bi, fi, direction, param, n=160):
        """Points along the isocurve, CLIPPED to the part of the face that is
        really there -- a preview that ran outside the trim curve would promise
        a cut where there is no surface."""
        try:
            from OCP.TopExp import TopExp
            from OCP.TopAbs import TopAbs_ShapeEnum, TopAbs_State
            from OCP.TopoDS import TopoDS
            from OCP.TopTools import TopTools_IndexedMapOfShape
            from OCP.BRepTools import BRepTools
            from OCP.BRep import BRep_Tool
            from OCP.BRepTopAdaptor import BRepTopAdaptor_FClass2d
            from OCP.gp import gp_Pnt2d
            proto = self.doc.protos.get(pk)
            if proto is None or bi >= len(proto.bodies):
                return []
            faces = TopTools_IndexedMapOfShape()
            TopExp.MapShapes_s(proto.bodies[bi], TopAbs_ShapeEnum.TopAbs_FACE,
                               faces)
            if fi < 1 or fi > faces.Extent():
                return []
            face = TopoDS.Face_s(faces.FindKey(fi))
            surf = BRep_Tool.Surface_s(face)
            u0, u1, v0, v1 = BRepTools.UVBounds_s(face)
            cls = BRepTopAdaptor_FClass2d(face, 1e-7)
            a, b = (v0, v1) if direction == "U" else (u0, u1)
            out = []
            for i in range(n + 1):
                t = a + (b - a) * i / n
                uv = (param, t) if direction == "U" else (t, param)
                if cls.Perform(gp_Pnt2d(*uv)) != TopAbs_State.TopAbs_IN:
                    continue
                p = surf.Value(*uv)
                out.append((p.X(), p.Y(), p.Z()))
            return out
        except Exception:
            return []

    def _face_uv_at(self, key, cell, point):
        """(proto key, body, B-rep face, u, v) for a click/hover, or None."""
        occ = self._occ_by_path.get(key[0])
        if occ is None or not self.doc:
            return None
        pk, bi = occ.proto_key, key[1]
        m = self._mesh_of(pk, bi)
        proto = self.doc.protos.get(pk)
        if m is None or proto is None or cell >= len(m.face_source):
            return None
        fi = m.face_source[cell]
        try:
            from OCP.TopExp import TopExp
            from OCP.TopAbs import TopAbs_ShapeEnum
            from OCP.TopoDS import TopoDS
            from OCP.TopTools import TopTools_IndexedMapOfShape
            from OCP.ShapeAnalysis import ShapeAnalysis_Surface
            from OCP.BRep import BRep_Tool
            from OCP.gp import gp_Pnt
            faces = TopTools_IndexedMapOfShape()
            TopExp.MapShapes_s(proto.bodies[bi], TopAbs_ShapeEnum.TopAbs_FACE,
                               faces)
            if fi < 1 or fi > faces.Extent():
                return None
            face = TopoDS.Face_s(faces.FindKey(fi))
            sas = ShapeAnalysis_Surface(BRep_Tool.Surface_s(face))
            uv = sas.ValueOfUV(gp_Pnt(*point), 1e-4)
            return pk, bi, fi, uv.X(), uv.Y()
        except Exception:
            return None

    def _preview_loopcut(self, got):
        """Draw every stretch of the cut under the cursor, before any click."""
        self._last_hover = got
        if got is None:
            self.viewport.clear_iso_preview()
            self.viewport.clear_snap_marker()
            self.viewport.set_action_cursor(None)
            self._hover_cut = None
            self._hover_doomed = ()
            self._draw_existing_cuts()
            return
        key, cell, point = got
        info = self._face_uv_at(key, cell, point)
        if info is None:
            self.viewport.clear_iso_preview()
            self.viewport.clear_snap_marker()
            self.viewport.set_action_cursor(None)
            return
        pk, bi, fi, u, v = info
        shift = bool(getattr(self.viewport, "_shift", False))
        # An EXISTING cut under the cursor takes priority and GLOWS, so it is
        # obvious that right-click will remove it rather than swap U/V.
        found = self._find_hovered_cut(pk, bi, fi, u, v)
        if found is not None:
            ci, si = found
            self._hover_cut = (pk, bi, ci, si)
            # Plain right-click takes the whole chain, so the whole chain
            # glows. With shift it takes a portion, and then ONLY that portion
            # may glow -- otherwise the highlight promises more than the click
            # delivers, which is the confusion Benn reported.
            n = len(self._iso_cuts[(pk, bi)][ci])
            if shift:
                self._hover_doomed = self._removal_set(pk, bi, ci, si,
                                                       self._remove_span)
            else:
                self._hover_doomed = set(range(n))
            self.viewport.clear_iso_preview()
            self.viewport.clear_snap_marker()
            self._draw_existing_cuts(hot=(pk, bi, ci, self._hover_doomed))
            self.viewport.set_action_cursor(self.viewport.DROP_CURSOR,
                                            len(self._hover_doomed))
            self._say(f"right-click removes {len(self._hover_doomed)} of "
                      f"{n} stretch(es)")
            return
        self._hover_cut = None
        self._hover_doomed = ()
        self._draw_existing_cuts()
        direction = self.cb_uv.currentText()
        param = u if direction == "U" else v
        snap = self._snap_for(pk, bi, fi, (u, v), direction) if shift else None
        kind = None
        if snap is not None:
            param, sp, kind = snap
            self.viewport.show_snap_marker(sp, self._snap_size(pk, bi))
            self.viewport.set_action_cursor(self.viewport.SNAP_CURSOR)
        else:
            self.viewport.clear_snap_marker()
            self.viewport.set_action_cursor(self.viewport.CUT_CURSOR)
        chain = self._cut_chain(pk, bi, fi, direction, param)
        strips = []
        for cf, cd, cp in chain:
            pts = self._iso_points(pk, bi, cf, cd, cp)
            if len(pts) >= 2:
                strips.append(pts)
        self.viewport.show_iso_preview(strips)
        note = f" (snapped to a {kind})" if snap is not None else ""
        if getattr(self, "_last_chain_closed", False):
            self._say(f"full loop detected, {len(chain)} tangential "
                      f"surfaces{note}")
        else:
            self._say(f"cut would cross {len(chain)} surface(s){note}")

    def _snap_size(self, pk, bi):
        """How big to draw the snap marker: a fraction of the body."""
        return max(1e-3, self._snap_reach(pk, bi) * 0.35)

    def _snap_reach(self, pk, bi):
        """How far a snap may pull the cut. Scaled to the BODY, so it means
        the same on a 3 mm screw and a 400 mm valve."""
        try:
            from OCP.Bnd import Bnd_Box
            from OCP.BRepBndLib import BRepBndLib
            key = ("reach", pk, bi)
            got = self._snap_cache.get(key)
            if got is None:
                bb = Bnd_Box()
                BRepBndLib.Add_s(self.doc.protos[pk].bodies[bi], bb, False)
                x0, y0, z0, x1, y1, z1 = bb.Get()
                got = self._snap_cache[key] = math.dist((x0, y0, z0),
                                                        (x1, y1, z1)) * 0.06
            return got
        except Exception:
            return 1.0

    def _snap_for(self, pk, bi, fi, uv, direction):
        """The nearest special point to snap to: (param, xyz, kind) or None.

        Measured in the CUT'S OWN PARAMETER, not in 3D, and that is the whole
        trick. What a click produces is an isocurve, so where the cursor sits
        ALONG that curve changes nothing -- only the parameter across it does.
        Comparing 3D distance instead makes the top line of a long cylinder
        unsnappable from anywhere but its very end, which is not how a CAD
        snap behaves.

        The parameter gap is turned into millimetres through the surface's own
        derivative, so the reach means the same thing on a 2 mm boss and a
        300 mm bore, and on a radian parameter as on a length one.
        """
        key = (pk, bi, fi)
        pts = self._snap_cache.get(key)
        if pts is None:
            try:
                from .. import tessellate as _T
                pts = _T.face_snap_points(self.doc.protos[pk].bodies[bi], fi)
            except Exception:
                pts = []
            self._snap_cache[key] = pts
        if not pts:
            return None
        scale, period = self._param_scale(pk, bi, fi, uv, direction)
        here = uv[0] if direction == "U" else uv[1]
        reach = self._snap_reach(pk, bi)
        best = None
        for x, y, z, su, sv, kind, graze_u, graze_v in pts:
            # A candidate whose isocurve is TANGENT to an edge here is not a
            # place to cut: the curve touches the boundary at one point instead
            # of crossing it, and the mesher is left with a hole. Measured on
            # the knob: open=1 nonmanifold=2 on exactly that parameter, clean
            # at all 19 others swept across the same face.
            if graze_u if direction == "U" else graze_v:
                continue
            p = su if direction == "U" else sv
            d = abs(p - here)
            if period:                     # a seam is not a wall: wrap round it
                d = min(d % period, period - d % period)
            d *= scale
            if d <= reach and (best is None or d < best[0]):
                best = (d, p, (x, y, z), kind)
        return None if best is None else (best[1], best[2], best[3])

    def _param_scale(self, pk, bi, fi, uv, direction):
        """(millimetres per unit of the cut parameter, period or 0)."""
        try:
            from OCP.TopExp import TopExp
            from OCP.TopAbs import TopAbs_ShapeEnum
            from OCP.TopoDS import TopoDS
            from OCP.TopTools import TopTools_IndexedMapOfShape
            from OCP.BRep import BRep_Tool
            from OCP.gp import gp_Pnt, gp_Vec
            faces = TopTools_IndexedMapOfShape()
            TopExp.MapShapes_s(self.doc.protos[pk].bodies[bi],
                               TopAbs_ShapeEnum.TopAbs_FACE, faces)
            surf = BRep_Tool.Surface_s(TopoDS.Face_s(faces.FindKey(fi)))
            p, du, dv = gp_Pnt(), gp_Vec(), gp_Vec()
            surf.D1(uv[0], uv[1], p, du, dv)
            d = du if direction == "U" else dv
            scale = math.sqrt(d.X() ** 2 + d.Y() ** 2 + d.Z() ** 2)
            if direction == "U":
                per = surf.UPeriod() if surf.IsUPeriodic() else 0.0
            else:
                per = surf.VPeriod() if surf.IsVPeriodic() else 0.0
            return (scale if scale > 1e-9 else 1.0), per
        except Exception:
            return 1.0, 0.0

    def _add_loopcut(self, key, cell, point, shift=False):
        """Click: cut here, snapped to a special point while shift is held.

        A left click NEVER removes anything -- see `_on_cut_rmb`.
        """
        info = self._face_uv_at(key, cell, point)
        if info is None:
            self._say("could not place the cut there")
            return
        pk, bi, fi, u, v = info
        direction = self.cb_uv.currentText()
        param = u if direction == "U" else v
        snapped = None
        if shift or getattr(self.viewport, "_shift", False):
            got = self._snap_for(pk, bi, fi, (u, v), direction)
            if got is not None:
                param, _sp, snapped = got
        chain = self._cut_chain(pk, bi, fi, direction, param)
        self._push_cut_undo()
        chains = list(self._iso_cuts.get((pk, bi), ()))
        chains.append(chain)
        self._iso_cuts[(pk, bi)] = chains
        note = f", snapped to a {snapped}" if snapped else ""
        if getattr(self, "_last_chain_closed", False):
            self._say(f"full loop detected, {len(chain)} tangential surfaces "
                      f"({len(chains)} cut(s) on this body){note}")
        else:
            self._say(f"loop cut {direction}={param:.4f} from face {fi}: "
                      f"{len(chain)} stretch(es), "
                      f"{len(chains)} cut(s) on this body{note}")
        self._retessellate()

    def _clear_loopcuts(self):
        """Drop every forced cut on the selected bodies."""
        targets = self._tuning_targets() or set(self._iso_cuts)
        self._push_cut_undo()
        n = 0
        for k in list(targets):
            if k in self._iso_cuts:
                n += sum(len(c) for c in self._iso_cuts.pop(k))
        self._say(f"cleared {n} loop cut(s)")
        if n:
            self._retessellate()

    def _recolor(self):
        mode = self.cb_color.currentIndex()
        if hasattr(self, "w_legend"):
            self.w_legend.setVisible(mode == self.SURFACE_TYPE_MODE)
        if self.doc and self.meshes:
            # Entering or leaving the surface-type mode changes the PER-CELL
            # colours, and `set_face_color_mode` only toggles scalar
            # visibility -- it does not upload anything. Without this the knob
            # stayed one flat colour, because a body with no material colours
            # has no cell scalars for the mode to reveal.
            was = getattr(self, "_last_color_mode", None)
            if self.SURFACE_TYPE_MODE in (mode, was) and mode != was:
                self.viewport.update_meshes(self.meshes, self._face_rgb)
            self._last_color_mode = mode
            self.viewport.set_colors(self._color_for)
            self.viewport.set_face_color_mode(self._face_colors_active)

    def _selected_keys(self) -> set:
        """Body keys under the current tree selection."""
        keys = set()
        for it in self.tree.selectedItems():
            data = it.data(0, Qt.UserRole)
            if not data:
                continue
            kind, path, bi = data
            if kind == "body":
                keys.add((path, bi))
            else:
                for (p, b) in self._body_items:
                    if p == path or p.startswith(path + "/"):
                        keys.add((p, b))
        return keys

    def _active_key(self):
        """The ACTIVE body: the last one clicked, as in Blender.

        Qt's `currentItem` already means exactly that -- the row the user last
        touched -- so there is no extra bookkeeping to keep in sync. It only
        counts when it is a body AND part of the selection; clicking a component
        leaves the active body alone.
        """
        it = self.tree.currentItem()
        if it is None:
            return None
        data = it.data(0, Qt.UserRole)
        if not data or data[0] != "body":
            return None
        key = (data[1], data[2])
        return key if key in self._selected_keys() else None

    def _selection_changed(self):
        if not self.doc:
            return
        keys = self._selected_keys()
        act = self._active_key()
        self.a_export_sel.setEnabled(bool(keys) and bool(self.meshes))
        self.viewport.highlight(keys, dim=self.c_isolate.isChecked(),
                                active=act)
        self._mark_active_row(act, keys)
        self.viewport.set_face_color_mode(self._face_colors_active)
        self._load_panel_from_selection(keys)

    def _mark_active_row(self, key, keys=None):
        """Paint the outliner the way Blender does: SELECTED rows in the
        selection colour, the ACTIVE one lighter and bold.

        Only the name column -- Status and Quality carry their own meaning
        ("open shell", "non-manifold", a preset name) and recolouring those
        would destroy information. `setForeground` emits itemChanged, so this
        runs behind `_tree_guard` or it reads as the user ticking a box.
        """
        if keys is None:
            keys = self._selected_keys()
        painted = getattr(self, "_painted_rows", set())
        want = set(keys)
        if want == painted and key == getattr(self, "_active_row", None):
            return
        self._tree_guard = True
        plain = QBrush(QColor(220, 220, 225))
        sel = QBrush(QColor(*[int(c * 255) for c in SELECTION_COLOR]))
        act = QBrush(QColor(*[int(c * 255) for c in ACTIVE_COLOR]))
        for k in painted - want:
            it = self._body_items.get(k)
            if it is not None:
                it.setForeground(0, plain)
                f = it.font(0)
                f.setBold(False)
                it.setFont(0, f)
        for k in want:
            it = self._body_items.get(k)
            if it is None:
                continue
            is_act = (k == key)
            it.setForeground(0, act if is_act else sel)
            f = it.font(0)
            f.setBold(is_act)
            it.setFont(0, f)
        self._painted_rows = want
        self._active_row = key
        self._tree_guard = False

    def _load_panel_from_selection(self, keys):
        """Show the selection's own quality, so it can be tweaked further."""
        seen = []
        for path, bi in keys:
            occ = self._occ_by_path.get(path)
            if occ is None:
                continue
            got = self._custom.get((occ.proto_key, bi))
            if got is None:
                return                  # not tuned: leave the panel alone
            seen.append(got)
        if not seen or any(q != seen[0] for q in seen[1:]):
            return                      # mixed: nothing sensible to show
        self._show_params(seen[0])

    def _show_params(self, q):
        """Fill the quality panel without triggering a re-tessellation."""
        self._loading_panel = True
        try:
            self.s_defl.set_value(q.deflection)
            self.s_angle.set_value(q.angle_deg)
            self.s_min.set_value(max(q.min_size, 0.0))
            self.s_aspect.set_value(q.grid_aspect)
            self.c_relative.setChecked(q.relative)
            self.c_structured.setChecked(q.structured)
            self.c_autogrid.setChecked(q.auto_grid)
            self.s_bias.set_value(q.grid_bias * 100.0)
            self.c_quads.setChecked(q.quads)
            self.c_iso.setChecked(q.lattice)
        finally:
            self._loading_panel = False

    def _item_checked(self, item, column):
        if self._tree_guard or column != 0 or not self.doc:
            return
        data = item.data(0, Qt.UserRole)
        if not data:
            return
        # itemChanged fires for BOTH an inline rename and a checkbox toggle, and
        # both live in column 0; a changed label means it was a rename.
        expected = self._expected_label(data)
        if expected is not None and item.text(0) != expected:
            self._tree_guard = True
            renamed = self._commit_rename(item, item.text(0))
            self._tree_guard = False
            if renamed:
                return
        checked = item.checkState(0) == Qt.Checked
        self._tree_guard = True
        self._apply_check(item, checked)
        self._tree_guard = False
        self._sync_hidden()

    def _expected_label(self, data):
        kind, path, bi = data
        if kind == "node":
            node = self._node_items.get(path)
            n = self.tree._node_of(node) if node is not None else None
            return n.name if n is not None else None
        occ = self._occ_by_path.get(path)
        if occ is None:
            return None
        proto = self.doc.protos.get(occ.proto_key)
        names = getattr(proto, "body_names", None) or [] if proto else []
        if bi < len(names) and names[bi]:
            return names[bi]
        return f"Body {bi + 1}"

    def _apply_check(self, item, checked):
        item.setCheckState(0, Qt.Checked if checked else Qt.Unchecked)
        for i in range(item.childCount()):
            self._apply_check(item.child(i), checked)

    def _sync_hidden(self):
        self._hidden = {k for k, it in self._body_items.items()
                        if it.checkState(0) != Qt.Checked}
        # Keep a copy keyed on the Node itself. Paths are built from names, so a
        # rename or a reparent renumbers every path-based key and the hide state
        # would silently reset on the next rebuild.
        self._hidden_nodes = set()
        for k, it in self._body_items.items():
            if it.checkState(0) == Qt.Checked:
                continue
            node = self.tree._node_of(it)
            if node is not None:
                self._hidden_nodes.add((id(node), k[1]))
        self.viewport.set_hidden(self._hidden)
        self._filter_rows(self._isolated)
        shown = len(self._body_items) - len(self._hidden)
        self.statusBar().showMessage(f"{shown} of {len(self._body_items)} bodies visible")

    def _hide_selection(self):
        """H: hide the selected bodies, as in Blender."""
        keys = self._selected_keys()
        if not keys:
            self._say("nothing selected to hide")
            return
        self._tree_guard = True
        for k in keys:
            it = self._body_items.get(k)
            if it is not None:
                it.setCheckState(0, Qt.Unchecked)
        self._tree_guard = False
        self._sync_hidden()
        self._say(f"hid {len(keys)} part(s)  (Alt+H shows everything)")

    def _frame_selection(self):
        """Numpad . : fit the selection, or everything if nothing is selected.

        Blender frames the whole selection, not just one part, so this takes the
        set rather than the active body.
        """
        keys = self._selected_keys() - self._hidden
        if keys:
            self.viewport.frame(keys)
            self._say(f"framed {len(keys)} part(s)")
        else:
            self.viewport.fit()
            self._say("framed everything")

    def _filter_rows(self, on: bool):
        """While ISOLATED, list only the parts that are on screen.

        Deliberately tied to isolate rather than to `_hidden` in general: a body
        hidden ad hoc with H stays listed, with its box unticked, so it can be
        brought back. Isolation is the mode where the rest are meant to be out
        of the way entirely.
        """
        self._tree_guard = True
        for k, it in self._body_items.items():
            it.setHidden(bool(on) and k in self._hidden)
        # a component with nothing visible under it goes too, or the tree is
        # full of empty branches
        for path, it in self._node_items.items():
            if not on:
                it.setHidden(False)
                continue
            it.setHidden(not any(
                k not in self._hidden for k in self._body_items
                if k[0] == path or k[0].startswith(path + "/")))
        self._tree_guard = False

    def _set_all_visible(self, visible: bool):
        if visible:
            self._isolated = False      # everything back in the list
        self._tree_guard = True
        for i in range(self.tree.topLevelItemCount()):
            self._apply_check(self.tree.topLevelItem(i), visible)
        self._tree_guard = False
        self._sync_hidden()

    def _toggle_isolate(self, checked=None):
        """Isolate the selection, or restore everything if already isolated."""
        if checked is None:
            checked = not self.b_isolate.isChecked()
            self.b_isolate.setChecked(checked)
        if not checked:
            self._set_all_visible(True)
            return
        if not self._isolate_selected():
            self.b_isolate.setChecked(False)

    def _refresh_tree_labels(self):
        """Repaint the Quality column without rebuilding the tree."""
        if not self.doc:
            return
        self._tree_guard = True
        for (path, bi), it in self._body_items.items():
            occ = self._occ_by_path.get(path)
            if occ is None:
                continue
            lvl = self._quality.get((occ.proto_key, bi))
            if lvl is None and (occ.proto_key, bi) in self._custom:
                lvl = "custom"
            it.setText(2, lvl or "")
        self._tree_guard = False

    def _isolate_selected(self):
        keys = self._selected_keys()
        if not keys:
            return False
        self._tree_guard = True
        for k, it in self._body_items.items():
            it.setCheckState(0, Qt.Checked if k in keys else Qt.Unchecked)
        for path, it in self._node_items.items():
            any_on = any(k in keys for k in self._body_items if k[0] == path
                         or k[0].startswith(path + "/"))
            it.setCheckState(0, Qt.Checked if any_on else Qt.Unchecked)
        self._tree_guard = False
        self._isolated = True
        self._sync_hidden()
        return True

