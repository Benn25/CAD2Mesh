    def _commit_rename(self, item, text):
        """Apply an inline edit. Returns True if it was a rename."""
        data = item.data(0, Qt.UserRole)
        if not data:
            return False
        kind, path, bi = data
        text = (text or "").strip()
        if not text:
            return False
        if kind == "node":
            node = self.tree._node_of(item)
            if node is None or node.name == text:
                return False
            node.name = text
            self._after_tree_edit()
            self.statusBar().showMessage(f"renamed to '{text}'")
            return True
        occ = self._occ_by_path.get(path)
        if occ is None:
            return False
        proto = self.doc.protos.get(occ.proto_key)
        if proto is None:
            return False
        names = list(getattr(proto, "body_names", []) or [])
        while len(names) < len(proto.bodies):
            names.append(None)
        if names[bi] == text:
            return False
        names[bi] = text
        proto.body_names = names
        self.statusBar().showMessage(f"renamed body to '{text}'")
        return True

