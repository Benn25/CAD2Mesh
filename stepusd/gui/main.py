    def _select_keys(self, keys, active=None):
        self.tree.blockSignals(True)
        self.tree.clearSelection()
        first = None
        for k in keys:
            it = self._body_items.get(k)
            if it is None:
                continue
            it.setSelected(True)
            if first is None:
                first = it
                par = it.parent()
                while par is not None:
                    par.setExpanded(True)
                    par = par.parent()
        act = self._body_items.get(active) if active is not None else None
        if act is not None:
            self.tree.setCurrentItem(act, 0, QItemSelectionModel.NoUpdate)
        self.tree.blockSignals(False)
        if first is not None:
            self.tree.scrollToItem(first)
        self._selection_changed()

