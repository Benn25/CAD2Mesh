    def _propagate_quality(self):
        """Copy the ACTIVE part's quality onto the rest of the selection.

        The active part is the last one clicked, exactly as in Blender, and it
        is drawn in a lighter shade so it is obvious which one is in charge.
        Both a preset and a tuned (custom) value propagate, whichever it has.
        """
        act = self._active_key()
        if act is None or not self.doc:
            self._say("no active part -- click one to make it the master")
            return
        occ = self._occ_by_path.get(act[0])
        if occ is None:
            return
        src = (occ.proto_key, act[1])
        lvl = self._quality.get(src)
        custom = self._custom.get(src)
        n = 0
        for path, bi in self._selected_keys():
            o = self._occ_by_path.get(path)
            if o is None:
                continue
            key = (o.proto_key, bi)
            if key == src:
                continue
            self._quality.pop(key, None)
            self._custom.pop(key, None)
            if custom is not None:
                self._custom[key] = custom
            elif lvl is not None:
                self._quality[key] = lvl
            n += 1
        self._refresh_tree_labels()
        self._recolor()
        self._retessellate()
        what = ("custom" if custom is not None
                else (lvl or "the global setting"))
        self._say(f"propagated {what} from the active part to {n} part(s)")

    def _set_quality(self, level):
        """Apply a quality level to every part in the selection."""
        if not self.doc:
            return
        targets = set()
        for path, bi in self._selected_keys():
            occ = self._occ_by_path.get(path)
            if occ is not None:
                targets.add((occ.proto_key, bi))
        if not targets:
            return
