    def open_step_path(self, path: str):
        """Load a STEP file by path (no dialog) -- also the scripting entry."""
        self.setWindowTitle(f"STEP -> USD  |  {os.path.basename(path)}")
        self.statusBar().showMessage(f"reading {os.path.basename(path)} ...")
        self.progress.setVisible(True)
        self.progress.setRange(0, 0)          # indeterminate; child process runs
        self._set_busy(True)
