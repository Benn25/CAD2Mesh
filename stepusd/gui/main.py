        self._update_body_flags()
        self._recolor()
        self._retessellate()
        self.statusBar().showMessage(
            f"{level or 'global'} quality on {len(protos)} bod(y/ies)"
            + (f"; {len(self._quality)} part(s) now differ from the default"
               if self._quality else ""))

