    def _loaded(self, doc):
        self._set_busy(False)
        self.doc = doc
        self.occurrences = flatten(doc)
        self._occ_by_path = {o.path: o for o in self.occurrences}
        self._sizes = None
        self._hidden = set()
        self._mesh_cache = {}
        # cuts and their snap candidates belong to the shapes of the OLD
        # document; a face index means nothing once the shapes have changed
        self._iso_cuts = {}
        self._cut_undo = []
        self._snap_cache = {}
        self._strip_cache = {}
        self._hover_cut = None
        self._hover_doomed = ()
        self._shutdown_pool()
        self.meshes = {}
        # Spin the workers up now, while the user is still looking at the tree,
        # instead of on the first slider drag.
        QTimer.singleShot(0, self._warm_pool)
        s = doc.stats()
        self.l_protos.setText(str(s["prototypes"]))
        self.l_occ.setText(f"{s['occurrences']}  ({s['instanced']} instanced)")
        nb = sum(len(p.bodies) for p in doc.protos.values())
        ns = sum(p.solid_bodies for p in doc.protos.values())
        no = s["open_bodies"]
        self.l_bodies.setText(f"{nb}  ({ns} solid"
                              + (f", {no} OPEN" if no else "") + ")")
        self.l_bodies.setStyleSheet("color:#d80" if no else "")
        self.l_bodies.setToolTip(
            "Open bodies are not closed solids, so they cannot be made "
            "watertight. Everything else is guaranteed sealed." if no else "")
        self._populate_tree()
        self._rebuild_palette()
        self._autoscale_defaults()
        # Freeze the default HERE. `_params_for` falls back to
        # `self._base or self._params()`, and `_params()` reads the LIVE panel,
        # so while _base stayed None every body with no override followed the
        # sliders -- which made isolating pointless: tuning 3 isolated bodies
        # re-meshed all 164. Measured exactly that before this line existed.
        self._base = self._params()
        sizes = self._body_sizes()
        if sizes:
            vals = sorted(sizes.values())
            # bound the slider by the actual smallest and biggest bodies, so the
            # whole travel lands on real parts
            self.s_size.set_range(vals[0], vals[-1])
            self.s_size.set_value(vals[len(vals) // 4])
            self._preview_size()
        self.viewport.clear()
        self._retessellate(force_rebuild=True)

    def _autoscale_defaults(self):
        """Pick a starting deviation from the model size, so the first view is
        sensible whether the part is a 3 mm screw or a 4 m frame."""
        from OCP.Bnd import Bnd_Box
        from OCP.BRepBndLib import BRepBndLib
        box = Bnd_Box()
        for p in self.doc.protos.values():
            # measure the BODIES, not proto.shape: documents restored from the
            # loader cache have no combined shape, only the per-body solids
            for b in p.bodies:
                try:
                    BRepBndLib.Add_s(b, box, False)
                except Exception:
                    pass
        if box.IsVoid():
            return
        # Default deviation from the BIGGEST BODY, not the whole assembly: the
        # assembly diagonal is dominated by how far apart the parts sit, which
        # says nothing about the detail in them. Calibrated so Benn's valve --
        # biggest body 318.2 mm across -- lands on 0.125 mm, then snapped to a
        # round number so the box shows something a person would have typed.
        biggest = 0.0
        for proto in self.doc.protos.values():
            for b in proto.bodies:
                bb = Bnd_Box()
                try:
                    BRepBndLib.Add_s(b, bb, False)
                except Exception:
                    continue
                if bb.IsVoid():
                    continue
                x0, y0, z0, x1, y1, z1 = bb.Get()
                biggest = max(biggest, x1 - x0, y1 - y0, z1 - z0)
        if biggest > 0:
            self._biggest_body = biggest
            defl = max(0.0005, min(20.0, _nice(biggest / 2500.0)))
            self.s_defl.set_value(defl)
            self.s_angle.set_value(30.0)
            # A manual floor on element size, rather than OCCT's auto MinSize.
            # Benn found this "improves the quality drastically quite often" and
            # the measurement agrees: at the valve's own defaults, slivers
            # (aspect > 4) fall 26.34% -> 23.42% and the worst aspect halves;
            # on the handle 42.73% -> 40.77% with FEWER polygons (141,893 ->
            # 136,212) and its two known non-manifold edges disappear.
            # Scaled off the deviation rather than hard-wired, so a 3 mm screw
            # does not get a floor sized for a 300 mm valve body. 1.6x lands the
            # valve on 0.2 mm: measured there against 0.1 mm it is better on
            # every axis at once -- slivers 24.77% -> 23.38%, polygons 239,065
            # -> 217,452, and 14% faster, HOLES=0. Benn goes to 0.3 by hand on
            # real parts and 0.3 is marginally better again (22.95%), but 0.35
            # turns back up, so the useful range tops out around there.
            self.s_min.set_value(max(0.0, min(5.0, _nice(defl * 1.6))))

    def _populate_tree(self):
        self._tree_guard = True
        self._pending_node_check = []
        self.tree.clear()
        self._body_items.clear()
        self._node_items.clear()
        self._nodes_by_id.clear()

        def add(node, parent, path):
            here = f"{path}/{node.name}" if path else node.name
            it = QTreeWidgetItem(parent)
            it.setText(0, node.name)
            # the name column elides to make the three columns fit, so the full
            # name has to stay reachable on hover
            it.setToolTip(0, node.name)
            it.setFlags(it.flags() | Qt.ItemIsUserCheckable | Qt.ItemIsEditable)
            it.setCheckState(0, Qt.Checked)
            self._pending_node_check.append((it, node))
            it.setData(0, Qt.UserRole, ("node", here, -1))
            nid = len(self._nodes_by_id) + 1
            self._nodes_by_id[nid] = node
            it.setData(0, Qt.UserRole + 1, nid)
            if node.proto is None:
                it.setForeground(0, QBrush(QColor(150, 190, 230)))
            self._node_items[here] = it
            if node.proto is not None:
                nb = len(node.proto.bodies)
                it.setText(1, f"{nb} bod{'y' if nb == 1 else 'ies'}")
                bnames = getattr(node.proto, "body_names", None) or []
                for bi in range(nb):
                    bit = QTreeWidgetItem(it)
                    label = (bnames[bi] if bi < len(bnames) and bnames[bi]
                             else f"Body {bi + 1}")
                    bit.setText(0, label)
                    bit.setToolTip(0, label)
                    bit.setFlags(bit.flags() | Qt.ItemIsUserCheckable
                                 | Qt.ItemIsEditable)
                    bit.setCheckState(
                        0, Qt.Unchecked
                        if (id(node), bi) in self._hidden_nodes else Qt.Checked)
                    bit.setData(0, Qt.UserRole, ("body", here, bi))
                    self._body_items[(here, bi)] = bit
            for ch in node.children:
                add(ch, it, here)
            return it

        for r in self.doc.roots:
            add(r, self.tree, "")
        # a component shows unchecked only when every body under it is hidden
        for it, node in reversed(self._pending_node_check):
            kids = [it.child(i) for i in range(it.childCount())]
            if kids and all(c.checkState(0) == Qt.Unchecked for c in kids):
                it.setCheckState(0, Qt.Unchecked)
        self.tree.expandToDepth(1)
        self._tree_guard = False

    def _update_body_flags(self):
        """Mark bodies that are not closed solids so they can be found."""
        if not self.doc:
            return
        self._tree_guard = True
        for (path, bi), item in self._body_items.items():
            occ = self._occ_by_path.get(path)
            m = None
            if occ is not None:
                ms = self.meshes.get(occ.proto_key)
                if ms and bi < len(ms):
                    m = ms[bi]
            if m is None:
                continue
            occ2 = self._occ_by_path.get(path)
            lvl = self._quality.get((occ2.proto_key, bi)) if occ2 else None
            if lvl is None and occ2 and (occ2.proto_key, bi) in self._custom:
                lvl = "custom"
            item.setText(2, lvl or "")
            item.setForeground(2, QBrush(QColor(150, 190, 230)))
            suffix = ""
            # A refused loop cut is not an error in the mesh -- it is a piece
            # of the user's intent that was thrown away to keep the body
            # sealed, and saying nothing would leave them staring at a cut
            # that is drawn in the viewport but absent from the mesh.
            if getattr(m, "iso_cuts_dropped", 0):
                suffix = "  cut refused"
            elif getattr(m, "iso_cuts_ineffective", 0):
                # The line is drawn but the surface did not divide. Saying
                # nothing leaves the user staring at a cut that is visibly
                # there and absent from the mesh, and working it out from the
                # picture -- which is exactly what happened.
                suffix = "  cut had no effect"
            if m.boundary_edges:
                # An open shell is already visible and already reported, so it
                # keeps its own label; the surface defect is still counted in
                # the Result panel. The sneaky case -- and the one this label
                # exists for -- is a defect with NO holes, which used to read as
                # perfectly watertight.
                item.setText(1, "open shell" + suffix)
                item.setForeground(1, QBrush(QColor(226, 150, 40)))
            elif getattr(m, "surface_defects", 0):
                item.setText(1, "SURFACE ERROR" + suffix)
                item.setForeground(1, QBrush(QColor(255, 90, 90)))
            elif m.nonmanifold_edges:
                item.setText(1, "non-manifold" + suffix)
                item.setForeground(1, QBrush(QColor(214, 74, 74)))
            else:
                item.setText(1, f"{len(m.tris):,} tris" + suffix)
                item.setForeground(1, QBrush(QColor(150, 150, 155)))
        self._tree_guard = False

