    def _retessellate(self, force_rebuild=False):
        """Queue a tessellation. Only ONE worker may run at a time: workers
        mutate the shared OCCT shapes, and two at once corrupts memory and
        kills the process silently. A request arriving mid-run replaces the
        pending one and is started when the current worker stops."""
        if not self.doc:
            return
        # With nothing selected and nothing isolated the panel IS the global
        # default, so pick it up here rather than only in `_param_changed`.
        # That signal fires on a user edit but not on a programmatic
        # `set_value`, and _params_for reads the frozen `_base` -- so without
        # this, "Apply now" after setting the widgets in code silently meshes
        # at the old values (caught by gui_smoke: 750 triangles at 0.01mm,
        # 1.0mm and everything between).
        if not self._tuning_targets():
            self._base = self._params()
        self._pending = (self._params(),
                         bool(force_rebuild) or not self.meshes)
        self._pump()

    def _ensure_pool(self):
        """A pool kept warm across re-tessellations: each worker re-reads the
        BRep cache once, so paying that on every slider drag would undo the win."""
        cache_dir = getattr(self.doc, "cache_dir", None)
        if not cache_dir:
            return None
        if self._pool is not None and self._pool_dir == cache_dir:
            return self._pool
        self._shutdown_pool()
        try:
            from concurrent.futures import ProcessPoolExecutor
            from .. import parallel as par
            n = par.worker_count()
            self._pool = ProcessPoolExecutor(
                max_workers=n, initializer=par.init_worker,
                initargs=(cache_dir,))
            self._pool_dir = cache_dir
            self._proto_index = {k: i for i, k in enumerate(self.doc.protos)}
        except Exception:
            self._pool = None
            self._pool_dir = None
        return self._pool

    def _warm_pool(self):
        """Start every worker now, rather than during the first re-tessellation.

        One submit spawns at most one process, so this fires one trivial task
        per worker. They land in the background; we never wait on them.
        """
        pool = self._ensure_pool()
        if pool is None:
            return
        try:
            from .. import parallel as par
            for _ in range(par.worker_count()):
                pool.submit(par.warm, None)
        except Exception:
            pass

    def _shutdown_pool(self):
        if self._pool is not None:
            try:
                self._pool.shutdown(wait=False, cancel_futures=True)
            except Exception:
                pass
        self._pool = None
        self._pool_dir = None

    def _pump(self):
        if self._worker is not None:
            self._worker.cancel()      # _worker_finished() will pick up _pending
            return
        if not self._pending:
            return
        _params, rebuild = self._pending
        self._pending = None
        self._rebuild = rebuild
        self._generation += 1
        gen = self._generation
        protos = list(self.doc.protos.values())
        w = TessellateWorker(protos, self._params_for, gen, self._mesh_cache,
                             pool=self._ensure_pool(),
                             proto_index=self._proto_index)
        self._worker = w               # strong ref: a GC'd running QThread aborts
        w.progress.connect(self._tess_progress)
        w.done.connect(lambda r, t, g=gen: self._tess_done(r, t, g))
        w.failed.connect(self._tess_failed)
        w.finished.connect(self._worker_finished)
        self.progress.setVisible(True)
        self.progress.setRange(0, w.total_bodies())
        w.start()

    def _stop_tessellation(self):
        """Abandon the run in progress and keep whatever already finished.

        Cancelling the worker THREAD is not enough, and this was the bug behind
        "once I stop with Esc I cannot tessellate any more". The bodies are
        meshed in a process pool, and `Future.cancel()` only drops work the
        executor has not yet handed to a worker -- it cannot stop one that is
        already running, and the executor has usually fed most of the batch
        into its call queue by then. Measured on the valve at 0.02 mm: of 53
        work items, cancelling removed 3 and left 50 still churning, so the next
        run queued behind all of them and took 1.6x as long as the same work on
        an idle pool. On a big model that is minutes, which reads exactly like a
        dead tool -- and the user pressed Stop precisely BECAUSE the run was
        too long.

        So the pool itself is thrown away: its processes are terminated, and a
        fresh one is built and warmed for the next run. That costs one pool
        spawn (~1.7s), paid while the user is reading the screen rather than
        while they are waiting.
        """
        self._pending = None          # do not immediately start another
        self._debounce.stop()         # or a queued edit restarts it at once
        w = self._worker
        if w is not None:
            w.cancel()                # set BEFORE the pool dies, so the
            self._discard_pool()      # BrokenProcessPool it raises is ignored
            self.statusBar().showMessage("tessellation stopped")
            self._say("tessellation stopped")
        else:
            self._say("nothing to stop")
        self.progress.setVisible(False)

    def _discard_pool(self):
        """Kill the pool outright and start a fresh one warming.

        The workers are mid-BRepMesh in C++, so there is nothing to poll a flag
        with: terminating the process is the only way to get the core back.
        Each worker holds its own read-only copy of the BRep and writes nothing
        outside itself, so losing one mid-body costs only that body's work.
        """
        pool = self._pool
        self._pool = None
        self._pool_dir = None
        if pool is not None:
            # TERMINATE first and do not call shutdown() at all. Measured:
            # shutdown(wait=False, cancel_futures=True) BEFORE terminating makes
            # the executor's manager thread drain the running tasks first, which
            # puts the cost right back on the cancelled run's size -- 2.3x, 2.9x
            # and 3.3x baseline for a cancelled 0.05 / 0.02 / 0.008 run, against
            # a flat 1.6x when the processes are simply killed.
            try:
                for proc in list(getattr(pool, "_processes", {}).values()):
                    proc.terminate()
            except Exception:
                pass
        # rebuild off the event loop so Esc stays instant
        QTimer.singleShot(0, self._warm_pool)

    def _worker_finished(self):
        self._worker = None
        if self._pending:
            self._pump()
        else:
            self.progress.setVisible(False)

    def closeEvent(self, ev):
        """Stop the worker before teardown, or Qt aborts on a running QThread."""
        self._pending = None
        self._shutdown_pool()
        if self._loader is not None:
            self._loader.cancel()
        w = self._worker
        if w is not None:
            w.cancel()
            w.wait(15000)
        super().closeEvent(ev)

