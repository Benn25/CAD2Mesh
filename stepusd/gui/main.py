    def _move_into_component(self):
        """Move the selected parts/bodies into a component chosen from a list."""
        if not self.doc:
            return
        nodes = self._selected_nodes()
        if not nodes:
            return
        choices = [("(top level - directly under the root)", None)]

        def walk(n, depth, path):
            if n.proto is None:
                choices.append(("    " * depth + n.name, n))
            for c in n.children:
                walk(c, depth + 1, path)

        for r in self.doc.roots:
            walk(r, 0, "")
        labels = [c[0] for c in choices]
        label, ok = QInputDialog.getItem(
            self, "Move into component",
            f"Move {len(nodes)} item(s) into:", labels, 0, False)
        if not ok:
            return
        target = dict(zip(labels, [c[1] for c in choices]))[label]
        moved = sum(1 for n in nodes if reparent(self.doc.roots, n, target))
        if moved:
            self._after_tree_edit()
            self.statusBar().showMessage(
                f"moved {moved} item(s) into {target.name if target else 'the top level'}")

